# Character fit table -> src/19_char_fit.js  (reads src/16_more_sprites.js; the character images are NOT changed)
# For every drawn walk / carry-walk frame: a vertical factor that brings the top of the head to the height of the
# idle pose shown for the same direction, so a cat does not sink or pop when it starts / stops walking and the
# 4-frame cycle does not hiccup. Factors are capped to [LO, HI] so heads never look stretched.
# Also: tray-point overrides where the cut data put the tray on the wrong side.
#   python3 tools/char_fit.py
import os,re,json,base64,io
import numpy as np
from PIL import Image
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LO,HI=.93,1.09
s=open(os.path.join(ROOT,'src','16_more_sprites.js'),encoding='utf-8').read(); M=json.loads(s[s.index('{'):s.rindex('}')+1])
# must match SHEET_REMAP in src/50_render.js: which idle art is shown per direction, and which walk art
SIDE={'idle':{90:(45,0),270:(315,0)},'walk':{45:(270,1),90:(270,1),315:(270,0)}}
REMAP={n:SIDE for n in M if n!='chef'}
REMAP['chef']={'idle':{270:(90,1)},'walk':{}}
REMAP['cat04']={'idle':{90:(45,0),270:(315,0),45:(315,1),135:(225,1)},'walk':SIDE['walk']}
def top(m):
    A=np.array(Image.open(io.BytesIO(base64.b64decode(m['src'].split(',')[1]))).convert('RGBA'))[...,3]>60
    ys=np.nonzero(A.any(1))[0]; return (m['ay']-ys.min())*m['s']
fit={}; report=[]
for n,c in M.items():
    rm=REMAP[n]; f={}
    idle_top={d:top(c['idle_%d'%rm['idle'].get(d,(d,0))[0]]) for d in range(0,360,45)}
    for d in range(0,360,45):
        for pre in ('walk','cwalk'):
            wd=rm['walk'].get(d,(d,0))[0] if pre=='walk' else d
            i=1
            while '%s%d_%d'%(pre,i,wd) in c:
                k='%s%d_%d'%(pre,i,wd); v=float(np.clip(idle_top[d]/top(c[k]),LO,HI))
                f.setdefault(k,{})[str(d)]=round(v,3); i+=1
    # the same frame can serve two directions (mirrored): keep one value per direction
    fit[n]=f
    for d in range(0,360,45):
        vals=[(k,v[str(d)]) for k,v in f.items() if str(d) in v and k.startswith('walk')]
        if vals: report.append('%-8s %3d idle %5.1f  walk %s'%(n,d,idle_top[d],' '.join('%.3f'%v for _,v in vals)))
tray={'chef':{'cwalk%d_180'%i:[.5,.5] for i in range(1,5)}}
js=('/* 19_char_fit.js — per-frame vertical fit of walk / carry-walk frames to the idle head height, and tray-point overrides.\n'
    '   AUTO-GENERATED by tools/char_fit.py from src/16_more_sprites.js (character art unchanged). */\n'
    'const CHAR_FIT='+json.dumps(fit,separators=(',',':'))+';\nconst CHAR_TRAY='+json.dumps(tray,separators=(',',':'))+';\n')
open(os.path.join(ROOT,'src','19_char_fit.js'),'w',encoding='utf-8').write(js)
print('\n'.join(report)); print(len(js),'bytes')
