def four_piece(im):
    # chicken box with 4 pieces: keep the striped box, repaint the heap as 4 drumstick balls tucked behind the rim
    A=np.array(im.convert('RGBA')).astype(int); h,w=A.shape[:2]; r,g,b=A[...,0],A[...,1],A[...,2]
    org=(r>170)&(g>80)&(g<200)&(b<110)&(r-b>90)
    yy=np.arange(h)[:,None]
    box=A.copy(); box[...,3]=np.where(org|(yy<h*.40),0,box[...,3])
    front=A.copy(); front[...,3]=np.where(org|(yy<h*.52),0,front[...,3])
    out=Image.new('RGBA',(w,h)); out.alpha_composite(Image.fromarray(box.astype(np.uint8)))
    d=_D.Draw(out); R=w*.17
    for cx,cy in [(.42,.30),(.66,.27),(.35,.42),(.60,.40)]:
        x,y=cx*w,cy*h
        d.ellipse([x-R,y-R,x+R,y+R],fill=(240,150,44,255),outline=(122,58,20,255),width=max(2,int(w*.025)))
        d.ellipse([x-R*.62,y-R*.7,x+R*.25,y+R*.1],fill=(255,196,96,255))
        for ox,oy in [(.3,.25),(-.2,.35),(.15,-.1)]: d.ellipse([x+ox*R-2,y+oy*R-2,x+ox*R+2,y+oy*R+2],fill=(200,110,30,255))
    out.alpha_composite(Image.fromarray(front.astype(np.uint8)))
    O=np.array(out).astype(int); hh=O.shape[0]; yy=np.arange(hh)[:,None]
    light=(O[...,:3].min(2)>170)&(yy>hh*.8)
